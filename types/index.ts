// Calendar sync types (Google Calendar API + Apple/iCloud CalDAV) --
// see lib/googleCalendar.ts, lib/appleCalendar.ts, app/actions/calendar.ts.
export type CalendarProvider = 'google' | 'apple' | 'local';
export type CalendarViewMode = 'day' | 'week' | 'month';

/** One individual calendar within a connected provider account (e.g. a
 * Google account's Primary/Work/Birthdays calendars, or an Apple CalDAV
 * collection), merged with this app's stored visibility/color preference. */
export interface CalendarInfo {
  provider: CalendarProvider;
  id: string; // provider's own calendar id / CalDAV collection URL
  // Which connected account (see ConnectedCalendarAccountsStatus) this
  // calendar came from -- undefined for the always-on local calendar.
  // Needed because a calendar id like Google's "primary" is only unique
  // WITHIN one account, not across every connected Google account.
  accountId?: string;
  accountLabel?: string; // e.g. the account's email/Apple ID, for display
  name: string;
  color: string;
  visible: boolean;
  writable: boolean;
  primary?: boolean;
}

/** A single event, normalized from either Google Calendar or an Apple
 * CalDAV VEVENT, for display in the unified Calendar tab. */
export interface UnifiedCalendarEvent {
  id: string;
  provider: CalendarProvider;
  calendarId: string;
  calendarName: string;
  calendarColor: string;
  title: string;
  description?: string;
  location?: string;
  start: string; // ISO 8601
  end: string; // ISO 8601
  allDay: boolean;
  writable: boolean;
}

export interface ConnectedCalendarAccount {
  id: string;
  label: string; // email (Google) or Apple ID (Apple)
  // Set when this account's calendars could not be fetched on the last
  // load (expired token, missing API scope/enablement, etc.) -- surfaced
  // as an inline warning in ConnectCalendarsPanel instead of that
  // account's calendars just silently not appearing in the toggle list.
  syncError?: string;
}

// Now a list per provider rather than a single connected/email pair --
// see the multi-account support added to GoogleDriveAuth/
// AppleCalendarAccount in prisma/schema.prisma.
export interface ConnectedCalendarAccountsStatus {
  google: { configured: boolean; accounts: ConnectedCalendarAccount[] };
  apple: { configured: boolean; accounts: ConnectedCalendarAccount[] };
}

