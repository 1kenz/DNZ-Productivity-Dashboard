// Full 5-level priority scale used everywhere a Todo's priority is set,
// grouped, colored, or charted (declared up top since Todo references it).
export type Priority = 'low' | 'medium' | 'high' | 'urgent' | 'routine';

export interface Todo {
  id: string;
  title: string;
  description?: string;
  completed: boolean;
  priority: Priority;
  projectId?: string;
  sectionId?: string; // Ana Bolum / Alt Bolum this task belongs to
  parentTodoId?: string; // set when this Todo is a microtask/subtask of another Todo
  tags?: string[];
  dueDate?: Date;
  deadline?: Date;
  status: string; // Dynamic status based on KanbanColumn
  recurringTaskId?: string; // set when this todo was generated by a RecurringTask
  targetCount?: number; // numeric-goal tracking, e.g. "500 kelime" -> targetCount=500
  currentCount?: number;
  unit?: string; // "kelime", "sayfa", "dakika", ...
  estimateHours?: number; // optional effort estimate for weighted progress rollups
  createdAt: Date;
  updatedAt: Date;
}

// Organizational layer between a Project and its Todos: Proje > Ana Bolum >
// Alt Bolum > Task > Mikro Task. Self-referencing (parentId) so a Section
// can contain SubSections with no fixed depth limit. A Section has no
// stored "completed" state of its own -- its progress is always derived
// from its tasks (see lib/progress.ts) to avoid state getting out of sync.
export interface Section {
  id: string;
  name: string;
  color?: string;
  icon?: string;
  order: number;
  projectId: string;
  parentId?: string;
  createdAt: Date;
  updatedAt: Date;
}

export type RecurrenceFrequency = 'daily' | 'weekly' | 'monthly';

export interface RecurringTask {
  id: string;
  title: string;
  description?: string;
  priority: Priority;
  projectId?: string;
  tags?: string[];
  frequency: RecurrenceFrequency;
  interval: number; // every N days / weeks / months
  daysOfWeek: number[]; // 0=Sun .. 6=Sat, used when frequency === 'weekly'
  dayOfMonth?: number; // used when frequency === 'monthly'
  startDate: Date;
  endDate?: Date;
  active: boolean;
  lastRunDate?: Date;
  createdAt: Date;
  updatedAt: Date;
}

export interface Project {
  id: string;
  name: string;
  color: string;
  icon?: string;
  createdAt: Date;
}

export interface KanbanColumn {
  id: string;
  name: string;
  color: string;
  order: number;
}

export interface Clock {
  id: string;
  city: string;
  timezone: string;
  emoji: string;
  order: number;
}

export interface LinkGroup {
  id: string;
  name: string;
  color: string;
  icon?: string;
  links: QuickLink[];
  order: number;
}

export interface QuickLink {
  id: string;
  title: string;
  url: string;
  icon?: string;
  groupId: string;
  order: number;
}

export interface PomodoroSession {
  id: string;
  duration: number;
  type: 'work' | 'break';
  startTime: Date;
  endTime?: Date;
  completed: boolean;
}

export interface Note {
  id: string;
  title: string;
  content: string;
  color?: string;
  createdAt: Date;
  updatedAt: Date;
}

export interface TimeEntry {
  id: string;
  projectId: string;
  taskId?: string;
  description?: string;
  duration: number; // in seconds
  createdAt: Date;
}

export interface ViewPreferences {
  taskView: 'list' | 'grid' | 'kanban';
  linkView: 'list' | 'grid';
  showCompleted: boolean;
  groupBy: 'none' | 'project' | 'priority' | 'date' | 'section' | 'status';
}

export interface AppState {
  todos: Todo[];
  projects: Project[];
  sections: Section[];
  recurringTasks: RecurringTask[];
  kanbanColumns: KanbanColumn[];
  clocks: Clock[];
  linkGroups: LinkGroup[];
  pomodoroSessions: PomodoroSession[];
  notes: Note[];
  timeEntries: TimeEntry[];
  viewPreferences: ViewPreferences;
  theme: 'light' | 'dark';
}

export type Theme = 'light' | 'dark';
export type TaskView = 'list' | 'grid' | 'kanban';
export type LinkView = 'list' | 'grid';

export const BACKUP_VERSION = 1;

export interface BackupPayload {
  version: number;
  exportedAt: string;
  data: {
    projects: any[];
    sections: any[];
    recurringTasks: any[];
    todos: any[];
    linkGroups: any[];
    quickLinks: any[];
    kanbanColumns: any[];
    clocks: any[];
    notes: any[];
    timeEntries: any[];
    viewPreferences: any[];
  };
}
