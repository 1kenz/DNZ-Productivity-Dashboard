'use client';

import React, { useState } from 'react';
import { useApp } from '@/contexts/AppContext';
import { Todo } from '@/types';
import styles from './TodoItem.module.css';

interface TodoItemProps {
  todo: Todo;
}

import { TaskDetailDrawer } from './TaskDetailModal';

export const TodoItem: React.FC<TodoItemProps> = ({ todo }) => {
  const { updateTodo, deleteTodo, toggleTodo, projects } = useApp();
  const [isEditing, setIsEditing] = useState(false);
  const [isDetailOpen, setIsDetailOpen] = useState(false);
  const [editTitle, setEditTitle] = useState(todo.title);

  const project = projects.find((p) => p.id === todo.projectId);

  const handleSave = () => {
    if (editTitle.trim()) {
      updateTodo(todo.id, { title: editTitle.trim() });
      setIsEditing(false);
    }
  };

  const handleKeyDown = (e: React.KeyboardEvent) => {
    if (e.key === 'Enter') {
      handleSave();
    } else if (e.key === 'Escape') {
      setEditTitle(todo.title);
      setIsEditing(false);
    }
  };

  const priorityColors = {
    urgent: '#991b1b',
    high: 'var(--color-error)',
    medium: 'var(--color-warning)',
    low: 'var(--color-success)',
    routine: '#4b5563',
  };

  const handleContentClick = (e: React.MouseEvent) => {
    // If double click for editing is handled by double-click event, 
    // single click can open the detail modal unless we are already editing.
    if (!isEditing) {
      setIsDetailOpen(true);
    }
  };

  return (
    <div className={`${styles.item} ${todo.completed ? styles.completed : ''}`}>
      <div className={styles.mainInfo}>
        <input
          type="checkbox"
          checked={todo.completed}
          onChange={() => toggleTodo(todo.id)}
          className={styles.checkbox}
        />

        <div className={styles.content}>
          {isEditing ? (
            <input
              type="text"
              value={editTitle}
              onChange={(e) => setEditTitle(e.target.value)}
              onBlur={handleSave}
              onKeyDown={handleKeyDown}
              className={styles.editInput}
              autoFocus
            />
          ) : (
            <div 
              className={styles.textContent} 
              onDoubleClick={() => setIsEditing(true)}
              onClick={handleContentClick}
            >
              <span className={styles.title}>{todo.title}</span>
              {todo.description && (
                <span className={styles.description}>{todo.description}</span>
              )}
              <div className={styles.tags}>
                {project && (
                  <span className={styles.projectTag} style={{ color: project.color }}>
                    {project.icon} {project.name}
                  </span>
                )}
                {todo.deadline && (
                  <span className={styles.deadlineTag}>
                    ⏰ {new Date(todo.deadline).toLocaleDateString()}
                  </span>
                )}
                {todo.recurringTaskId && (
                  <span className={styles.recurringTag} title="Generated by a recurring task">
                    🔁 Recurring
                  </span>
                )}
              </div>
            </div>
          )}
        </div>

        <div className={styles.rightSide}>
          <div className={styles.priorityContainer}>
            <div
              className={styles.priorityDot}
              style={{ backgroundColor: priorityColors[todo.priority] }}
              title={todo.priority}
            />
            <span className={styles.priorityLabel}>{todo.priority}</span>
          </div>
          
          <div className={styles.actions}>
            <button
              className={styles.actionBtn}
              onClick={() => setIsEditing(true)}
              title="Edit Inline"
            >
              ✏️
            </button>
            <button
              className={`${styles.actionBtn} ${styles.deleteBtn}`}
              onClick={() => deleteTodo(todo.id)}
              title="Delete"
            >
              🗑️
            </button>
          </div>
        </div>
      </div>

      <TaskDetailDrawer 
        todo={todo} 
        isOpen={isDetailOpen} 
        onClose={() => setIsDetailOpen(false)} 
      />
    </div>
  );
};
