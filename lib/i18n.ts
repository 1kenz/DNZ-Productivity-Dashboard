export type TranslationKey = keyof typeof DICTIONARIES.en | string;

export function t(key: TranslationKey, lang: Language = 'en', params?: Record<string, string | number>): string {
  const dict = DICTIONARIES[lang] || DICTIONARIES.en;
  let text = (dict as any)[key] || (DICTIONARIES.en as any)[key] || key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }

  return text;
}
